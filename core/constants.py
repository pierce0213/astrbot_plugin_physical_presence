def normalize_holder(value: str, default: str = "table") -> str:
    """把中文/英文的持有位置统一成内部 key。"""

    text = str(value or "").strip()
    if not text:
        return default
    if text in HOLDER_LABELS:
        return text
    if text in HOLDER_ALIASES:
        return HOLDER_ALIASES[text]
    for alias, key in HOLDER_ALIASES.items():
        if alias and alias in text:
            return key
    return default
